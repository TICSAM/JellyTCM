      const p = String(raw).replace(/[（(][^）)]*[）)]/g,'').trim() || String(raw);
      if(sp[p]) { out.push({p, w:sp[p]}); continue; }
      const sk = Object.keys(sp).find(k=>p.indexOf(k)>=0);
      if(sk) { out.push({p, w:sp[sk]}); continue; }
      for(const r of this.rules){
        if(r.re.test(p)) { out.push({p, w:r.w}); break; }
      }
